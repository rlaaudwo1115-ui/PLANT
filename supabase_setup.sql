-- 1. projects 테이블 생성
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  title text not null,
  author text not null,
  year text default '2026',
  grade int default 1,
  semester int default 1,
  category text default 'studio',
  type text default 'Architecture',
  thumbnail text not null,
  detail_images text[] default '{}',
  description text default ''
);

-- 2. 관리자 목록 테이블 (여기에 등록된 이메일로 로그인한 사람만 업로드/삭제 가능)
create table if not exists public.admins (
  email text primary key
);
alter table public.admins enable row level security;
-- admins 테이블에는 정책을 만들지 않음 → 웹사이트(anon/로그인 사용자)에서는 읽기/수정 불가

-- 현재 로그인한 사용자가 관리자인지 확인하는 함수
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where lower(email) = lower(auth.jwt() ->> 'email')
  );
$$;

