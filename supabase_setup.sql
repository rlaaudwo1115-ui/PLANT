-- 3. projects 테이블 권한(RLS): 조회는 누구나, 등록/수정/삭제는 관리자만
alter table public.projects enable row level security;

drop policy if exists "Enable read access for all users" on public.projects;
create policy "Enable read access for all users"
on public.projects for select
using (true);

drop policy if exists "Enable insert access for all users" on public.projects;
drop policy if exists "Admins can insert" on public.projects;
create policy "Admins can insert"
on public.projects for insert
to authenticated
with check (public.is_admin());

drop policy if exists "Admins can update" on public.projects;
create policy "Admins can update"
on public.projects for update
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "Enable delete access for all users" on public.projects;
drop policy if exists "Admins can delete" on public.projects;
create policy "Admins can delete"
on public.projects for delete
to authenticated
using (public.is_admin());

-- 4. 이미지 저장용 public Storage 버킷 ('project-images')
insert into storage.buckets (id, name, public)
values ('project-images', 'project-images', true)
on conflict (id) do update set public = true;

-- 5. Storage 권한: 이미지 보기는 누구나, 업로드/삭제는 관리자만
drop policy if exists "Public Access for project-images" on storage.objects;
create policy "Public Access for project-images"
on storage.objects for select
using (bucket_id = 'project-images');

drop policy if exists "Public Upload for project-images" on storage.objects;
drop policy if exists "Admin Upload for project-images" on storage.objects;
create policy "Admin Upload for project-images"
on storage.objects for insert
to authenticated
with check (bucket_id = 'project-images' and public.is_admin());

drop policy if exists "Public Delete for project-images" on storage.objects;
drop policy if exists "Admin Delete for project-images" on storage.objects;
create policy "Admin Delete for project-images"
on storage.objects for delete
to authenticated
using (bucket_id = 'project-images' and public.is_admin());
